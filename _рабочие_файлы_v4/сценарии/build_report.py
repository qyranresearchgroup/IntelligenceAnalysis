def esc(s):
    return (s or '').replace('|', '\\|').replace('\n', ' ').strip()


def cut(s, n):
    s = (s or '').replace('\n', ' ').strip()
    return s if len(s) <= n else s[:n].rstrip() + '…'


def load_cycle(c):
    d = json.load(open(V4 / f'results_c{c}.json'))
    rs = d['results'] if isinstance(d, dict) else d
    doc = d.get('doc') if isinstance(d, dict) else None
    return [r for r in rs if r], doc


def doc_items_early(c):
    """DOC-замечания c1–c3 лежат в cross_after_c<N>.json (словарь адресат → список)."""
    x = json.load(open(V4 / f'cross_after_c{c}.json'))
    items = []
    for tgt, lst in x.items():
        for i in lst:
            if str(i.get('from', '')).upper().startswith('DOC'):
                items.append({**i, 'target': tgt})
    return items


