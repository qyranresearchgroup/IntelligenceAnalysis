def classify(text):
    for k, _, rx in CATS:
        if re.search(rx, text): return k
    return 'other'
def load_pass(p):
    pat = 'confirmed' if p != 'v3' else 'findings'
    out = []
    for f in sorted(glob.glob(f'v4/{p}/{pat}_*.json')):
        sid = re.search(r'_(S\d\d|SAPP)\.json', f).group(1)
        for x in json.load(open(f)):
            out.append({**x, 'sid': sid})
    return out
if __name__ == '__main__':
    tot = collections.Counter(); bysev = collections.defaultdict(collections.Counter)
    for p in ['v1','v2','v3','v4p']:
        items = load_pass(p); c = collections.Counter()
        for x in items:
            k = classify(x['point'] + ' ' + x.get('explanation','')[:300]); c[k]+=1; tot[k]+=1; bysev[k][x['severity']]+=1
