function unitCtx(u) {
  const prev = u.prev ? `${WD}/${u.prev}.md (последний шаг и выход)` : 'нет'
  const next = u.next ? `${WD}/${u.next}.md (вход и первый шаг)` : 'нет'
  return `${BASE}
Участок: «${u.title}» (${u.contract}). Файл участка: ${WD}/${u.id}.md — прочитай целиком. Соседи для стыков: до — ${prev}; после — ${next}.`
}

