const CACHED = A.cached_files || {}   // готовые результаты прерванного прохода: метка → файл JSON
async function call(prompt, opts) {
  if (CACHED[opts.label]) {
    const r0 = await agent(`Прочитай файл ${CACHED[opts.label]} (JSON — готовый результат рецензента) и верни его содержимое по схеме дословно, без изменений, ничего не добавляя и не убирая. Никакие файлы не редактируй.`, { ...opts, label: `${opts.label}:cached`, effort: EFF })
    if (r0) { log(`${opts.label}: взят готовый результат прерванного прохода`); return r0 }
  }
  let r = await agent(prompt, opts)
  if (!r) r = await agent(prompt, { ...opts, label: `${opts.label}:retry` })
  return r
}

const results = await pipeline(A.units, async (u) => {
  const rs = await parallel(LENSES.map(([k, t]) => () =>
    call(reviewPrompt(u, t), { label: `review:${u.id}:${k}:${TAG}`, phase: 'Find', schema: FIND_SCHEMA, effort: EFF }).then(r => r ? { ...r, lens: k } : null)))
  const ok = rs.filter(Boolean)
  if (ok.length < LENSES.length) {
    log(`${u.id} ${TAG}: рецензентов ${ok.length}/${LENSES.length} — участок НЕ проверен до конца`)
    return { id: u.id, status: 'incomplete', note: `рецензентов ${ok.length}/${LENSES.length}` }
  }
  const findings = []
  ok.forEach(r => (r.findings || []).forEach(f => findings.push({ ...f, lens: r.lens })))
  findings.forEach((f, i) => { f.idx = i })
  if (!findings.length) { log(`${u.id} ${TAG}: замечаний нет`); return { id: u.id, status: 'clean', found: 0, confirmed: 0 } }
  const vs = (await parallel(ROLES.map(([rk, rt]) => () =>
    call(verifyPrompt(u, rt, findings), { label: `verify:${u.id}:${rk}:${TAG}`, phase: 'Verify', schema: VERIFY_SCHEMA, effort: EFF })))).filter(Boolean)
  if (vs.length < 2) {
    log(`${u.id} ${TAG}: верификаторов ${vs.length}/3 — участок НЕ проверен до конца`)
    return { id: u.id, status: 'incomplete', found: findings.length, note: `верификаторов ${vs.length}/3` }
  }
  const confirmed = []
  findings.forEach(f => {
    const yes = vs.map(v => (v.verdicts || []).find(x => x.idx === f.idx)).filter(v => v && v.confirmed)
    if (yes.length >= 2) confirmed.push({ ...f, refined: yes.map(v => v.refined_fix), points: yes.map(v => v.correct_point) })
  })
  const sev = {}
  confirmed.forEach(f => { sev[f.severity] = (sev[f.severity] || 0) + 1 })
  const byLens = {}
  confirmed.forEach(f => { byLens[f.lens] = (byLens[f.lens] || 0) + 1 })
  log(`${u.id} ${TAG}: найдено ${findings.length}, подтверждено ${confirmed.length} ${JSON.stringify(sev)}`)
  if (!confirmed.length) return { id: u.id, status: 'clean', found: findings.length, confirmed: 0 }
  const BATCH = 20
  const outs = []
  for (let b = 0; b * BATCH < confirmed.length; b++) {
    const part = confirmed.slice(b * BATCH, (b + 1) * BATCH)
    const nb = Math.ceil(confirmed.length / BATCH)
    const note = b === 0 ? '' : `\nЭто пачка ${b + 1} из ${nb}: предыдущие пачки этого прохода уже внесены, резервную копию НЕ перезаписывай; цитаты могли сместиться — находи место по смыслу; если замечание уже снято предыдущей правкой, пропусти его и назови.`
    const fxb = await call(fixPrompt(u, part).replace('Верни сводку по схеме.', note + '\nВерни сводку по схеме.').replace(b === 0 ? '@@' : `СНАЧАЛА сохрани резервную копию: mkdir -p ${WD}/_bak && cp ${WD}/${u.id}.md ${WD}/_bak/${u.id}_${TAG}.md`, b === 0 ? '@@' : 'Резервная копия этого прохода уже сделана.'), { label: `fix:${u.id}:${TAG}:b${b + 1}`, phase: 'Fix', schema: FIX_SUMMARY, effort: EFF })
    if (!fxb) {
      log(`${u.id} ${TAG}: пачка ${b + 1}/${nb} не внесена`)
      return { id: u.id, status: 'incomplete', found: findings.length, confirmed: confirmed.length, sev, byLens, done_batches: b, outs, note: 'правщик не вернул результат' }
    }
    outs.push(fxb)
  }
  const fx = { applied: outs.reduce((s, x) => s + x.applied, 0), not_applied: outs.reduce((s, x) => s + x.not_applied, 0), notes: outs.map((x, i) => `[пачка ${i + 1}] ${x.notes}`).join('\n\n') }
  return { id: u.id, status: 'fixed', found: findings.length, confirmed: confirmed.length, sev, byLens, applied: fx.applied, not_applied: fx.not_applied, notes: fx.notes }
})

const done = results.filter(Boolean)
const byStatus = {}
done.forEach(d => { byStatus[d.status] = (byStatus[d.status] || 0) + 1 })
const total = done.reduce((s, d) => s + (d.confirmed || 0), 0)
log(`Проход ${TAG}: статусы ${JSON.stringify(byStatus)}; подтверждено всего ${total}`)
return { tag: TAG, byStatus, total, done }
